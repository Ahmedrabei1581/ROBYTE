// Enforce download headers for .zip archives inside iframe previews
const downloadHeadersPlugin: Plugin = {
  name: 'download-headers',
  configureServer(server) {
    server.middlewares.use((req, res, next) => {
      if (req.url && (req.url.startsWith('/dev-sw.js') || req.url.startsWith('/sw.js'))) {
        res.setHeader('Content-Type', 'application/javascript; charset=utf-8');
        res.setHeader('Cache-Control', 'no-store, no-cache, must-revalidate');
        res.end(`
self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.map((k) => caches.delete(k))))
      .then(() => self.registration.unregister())
      .then(() => self.clients.matchAll({ type: 'window' }))
      .then((clients) => clients.forEach((client) => client.navigate(client.url)))
  );
});
`);
        return;
      }
      if (req.url && (req.url.endsWith('.zip') || req.url.includes('.zip?'))) {
        const cleanName = path.basename(req.url.split('?')[0]);
        res.setHeader('Content-Disposition', `attachment; filename="${cleanName}"`);
        res.setHeader('Content-Type', 'application/zip');
        res.setHeader('Access-Control-Allow-Origin', '*');
      }
      next();
    });
  },
};

